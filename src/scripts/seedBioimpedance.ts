async function seedBioimpedance(): Promise<void> {
  console.log('🧬 Iniciando ingestão histórica de Bioimpedância...');
  
  const athlete = await athleteRepository.getPrimaryAthlete();
  if (!athlete) {
    console.error('❌ Comandante não encontrado. Abortando operação.');
    process.exit(1);
  }

  const lines = csvData.trim().split('\n');
  const records: BioimpedanceRow[] = [];

  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;

    const columns = line.split(';');
    
    // Regra Tática 1: Combinação de Data YYYY-MM-DD
    const ano = columns[0];
    const dataStr = columns[1];
    const recordDate = new Date(`${ano}-${dataStr}T12:00:00.000Z`);

    // Regra Tática 3: Parseamento Estrito e Defensivo
    const weight = parseFloat(columns[2]);
    const bodyFat = parseFloat(columns[3]);
    
    // Regra Tática 2: Fallback visceral_fat
    const visceralRaw = columns[10]?.trim();
    const visceralFat = visceralRaw ? parseFloat(visceralRaw) : 14.0;

    if (Number.isNaN(weight) || Number.isNaN(bodyFat)) {
      console.warn(`⚠️ Linha ${i} ignorada devido a erro de conversão numérica.`);
      continue;
    }

    records.push({
      athleteId: athlete.id,
      date: recordDate,
      weight,
      bodyFat,
      muscleMass: parseFloat(columns[4]),
      bodyWater: parseFloat(columns[5]),
      metabolicAge: parseInt(columns[6], 10),
      tmb: parseFloat(columns[7]),
      protein: parseFloat(columns[8]),
      boneMass: parseFloat(columns[9]),
      visceralFat,
    });
  }

  if (records.length === 0) {
    console.log('Nenhum dado válido para ingestão.');
    process.exit(0);
  }

  try {
    // Regra Tática 4: Blindagem contra duplicidade
    await db.insert(bioimpedanceLogs)
      .values(records)
      .onConflictDoNothing({ 
        target: [bioimpedanceLogs.athleteId, bioimpedanceLogs.date] 
      });
      
    console.log(`✅ Ingestão concluída com sucesso: ${records.length} registros processados.`);
  } catch (error) {
    console.error('❌ Falha na inserção do Drizzle ORM:', error);
  }
  
  process.exit(0);
}

